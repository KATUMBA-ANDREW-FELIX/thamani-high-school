function load_alumni_page_content($connection): array
{
    $defaults = alumni_default_page_content();
    $stmt = thamani_db_prepare($connection, 'SELECT content_json FROM alumni_page_content WHERE id = 1 LIMIT 1');
    if (!$stmt) {
        error_log('[Alumni Page Content Prepare] ' . thamani_db_error($connection));
        return $defaults;
    }

    if (!thamani_db_stmt_execute($stmt)) {
        error_log('[Alumni Page Content Fetch] ' . thamani_db_stmt_error($stmt));
        thamani_db_stmt_close($stmt);
        return $defaults;
    }

    $result = thamani_db_stmt_get_result($stmt);
    $row = $result ? thamani_db_fetch_assoc($result) : null;
    thamani_db_stmt_close($stmt);
    if (!$row || !is_string($row['content_json'] ?? null)) {
        return $defaults;
    }

    $stored = json_decode($row['content_json'], true);
    if (!is_array($stored)) {
        error_log('[Alumni Page Content Decode] Stored page content is invalid JSON.');
        return $defaults;
    }

    $content = array_replace($defaults, $stored);
    $rowFields = [
        'stats' => ['value', 'label'],
        'benefits' => ['title', 'description'],
        'achievements' => ['year', 'title', 'description'],
        'leaders' => ['role', 'name', 'meta', 'description'],
        'projects' => ['code', 'status', 'title', 'description', 'progress_label', 'progress'],
        'workplan_phases' => ['label', 'title'],
        'registration_steps' => ['title', 'description'],
    ];
    foreach ($defaults as $key => $defaultValue) {
        if (is_array($defaultValue)) {
            if (!is_array($content[$key])) {
                $content[$key] = $defaultValue;
                continue;
            }
            $rows = [];
            foreach ($content[$key] as $row) {
                if (!is_array($row)) {
                    continue;
                }
                foreach ($rowFields[$key] ?? [] as $field) {
                    $row[$field] = is_scalar($row[$field] ?? null) ? (string)$row[$field] : '';
                }
                if ($key === 'workplan_phases') {
                    $items = is_array($row['items'] ?? null) ? $row['items'] : [];
                    $row['items'] = array_values(array_map('strval', array_filter($items, 'is_scalar')));
                }
                $rows[] = $row;
            }
            $content[$key] = $rows;
        } elseif (!is_scalar($content[$key])) {
            $content[$key] = $defaultValue;
        } else {
            $content[$key] = (string)$content[$key];
        }
    }

    return $content;
}

function alumni_page_escape($value): string
{
    return htmlspecialchars(is_scalar($value) ? (string)$value : '', ENT_QUOTES, 'UTF-8');
}
